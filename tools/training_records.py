"""Writes the records of a training run in training/, and models/manifest.json, from the run's folder.

    python tools/training_records.py RUN_DIR

RUN_DIR is the run's folder (runs/r1); the files are named after it. It writes:

- training/<run>-config.json: the run's config.json, unchanged.
- training/<run>-metrics.csv: metrics.jsonl as a table, one row per logged step. A restart after a
  crash resumes from the last saved state, so a few steps were logged twice; the last row of each
  is kept.
- training/<run>-events.txt: the lines of log.txt that are not a logged step: starts, stops, crashes.
- training/<run>-selfplay.csv: the self-play games of selfplay/games.jsonl (several GB, read once,
  line by line) per block of 2,000: results, mean length, how the games ended, and the training
  step at which the trainer had counted that many games.
- models/manifest.json: for each of the two checkpoints the results use, read from the run's
  checkpoints/ folder (they are not distributed), its size, SHA-256, step, samples and games
  generated by then (from the metrics; the checkpoint's own counters must agree), and date.
"""

from __future__ import annotations

import argparse
import bisect
import collections
import csv
import hashlib
import io
import json
import pickle
import re
import shutil
import sys
import zipfile
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TRAINING = ROOT / "training"
MODELS = ROOT / "models"
BLOCK = 2000
REASONS = ("KingEscaped", "ExitFort", "KingCaptured", "Encircled", "Repetition", "NoMoves")
METRICS = {  # column: decimals kept (None for an integer)
    "time": 1,
    "step": None,
    "generated": None,
    "games": None,
    "lr": 6,
    "mean_plies": 2,
    "attacker_wins": 4,
    "undecided": 4,
    "loss": 4,
    "policy": 4,
    "policy_kl": 4,
    "opponent": 4,
    "value": 4,
    "q": 4,
    "moves_left": 4,
}
STEP_LINE = re.compile(r"^\d{4}-\d\d-\d\d \d\d:\d\d:\d\d step \d+ \|")
# What each checkpoint in the manifest is (docs/RESULTS.md).
CHECKPOINTS = {
    36000: "The network of the first match against TaflZero at 15 s per move, which also played it at 1 s "
    "per move, and the lowest rung of the checkpoint ladder.",
    468000: "The network of the second match against TaflZero at 15 s per move, and the highest rung of the "
    "checkpoint ladder.",
}


def number(value: float, decimals: int | None) -> str:
    """A value of the metrics as written in the table."""
    if decimals is None:
        return str(int(value))
    return f"{value:.{decimals}f}".rstrip("0").rstrip(".")


def metrics_rows(path: Path) -> list[dict[str, Any]]:
    """The metrics, one row per step (the last logged), in the order of the steps."""
    last: dict[int, dict[str, Any]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        row = json.loads(line)
        last[row["step"]] = row
    return [last[step] for step in sorted(last)]


def metrics_csv(rows: list[dict[str, Any]]) -> str:
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(METRICS)
    for row in rows:
        writer.writerow([number(row[key], decimals) for key, decimals in METRICS.items()])
    return out.getvalue()


def events(path: Path) -> str:
    """The lines of the training log that are not a logged step."""
    lines = path.read_text(encoding="utf-8").splitlines()
    return "".join(f"{line}\n" for line in lines if not STEP_LINE.match(line))


def selfplay_blocks(path: Path) -> tuple[list[dict[str, Any]], int, int]:
    """The self-play games per block of BLOCK, read once, line by line. Lines torn by a crash
    (a restart ends them with a line break) and a last line still being written are left out.
    Returns the blocks, the number of torn lines and whether the last line was left out."""
    blocks: list[dict[str, Any]] = []
    torn = partial = 0
    block: dict[str, Any] = {}
    games = 0
    with open(path, "rb") as f:
        for line in f:
            if not line.endswith(b"\n"):
                partial = 1
                break
            try:
                game = json.loads(line)
            except json.JSONDecodeError:
                torn += 1
                continue
            if games % BLOCK == 0:
                block = {"first_game": games + 1, "games": 0, "plies": 0, "winners": Counter(), "reasons": Counter()}
                blocks.append(block)
            games += 1
            block["games"] += 1
            block["plies"] += game["plies"]
            block["winners"][game["winner"]] += 1
            block["reasons"][game["reason"]] += 1
    return blocks, torn, partial


def selfplay_csv(blocks: list[dict[str, Any]], rows: list[dict[str, Any]]) -> str:
    """The blocks as a table. A block's approx_step is the first logged step at which the trainer
    had counted as many games as the file holds up to the end of the block."""
    counted, steps = [], []
    for row in rows:  # the counter goes back a little after a crash; keep it non-decreasing
        counted.append(max(row["games"], counted[-1] if counted else 0))
        steps.append(row["step"])
    seen = {reason for block in blocks for reason in block["reasons"]}
    others = sorted(str(r) for r in seen - set(REASONS) - {None})
    # An unfinished game (stopped at the ply limit) has no reason; a column for that only if a
    # finished game also lacks one.
    reasonless = any(b["reasons"][None] != b["winners"][None] for b in blocks)
    reasons = [*REASONS, *others] + (["no_reason"] if reasonless else [])
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(
        ["first_game", "games", "attacker_wins", "defender_wins", "unfinished", "mean_plies", *reasons, "approx_step"]
    )
    for b in blocks:
        end = b["first_game"] + b["games"] - 1
        i = bisect.bisect_left(counted, end)
        by_reason = [b["reasons"][None if r == "no_reason" else r] for r in reasons]
        writer.writerow(
            [
                b["first_game"],
                b["games"],
                b["winners"]["attackers"],
                b["winners"]["defenders"],
                b["winners"][None],
                f"{b['plies'] / b['games']:.1f}",
                *by_reason,
                steps[i] if i < len(steps) else "",
            ]
        )
    return out.getvalue()


class _Stub:
    """Stands for any object of a checkpoint's pickle other than its plain values."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        pass

    def __setstate__(self, state: Any) -> None:
        pass


class _CountersOnly(pickle.Unpickler):
    """Reads a PyTorch checkpoint's pickle without PyTorch: tensors and other objects become
    stubs, so only plain values (the trainer's counters) are read, and no code is run."""

    def find_class(self, module: str, name: str) -> Any:
        if (module, name) == ("collections", "OrderedDict"):
            return collections.OrderedDict
        return _Stub

    def persistent_load(self, pid: Any) -> None:
        return None


def checkpoint_counters(path: Path) -> dict[str, Any]:
    """The plain values that a checkpoint written by tafl.train holds (steps, generated, games, ...)."""
    with zipfile.ZipFile(path) as archive:
        name = next(n for n in archive.namelist() if n.endswith("/data.pkl"))
        data = _CountersOnly(io.BytesIO(archive.read(name))).load()
    return {key: value for key, value in data.items() if isinstance(value, (int, float, str))}


def manifest(rows: list[dict[str, Any]], checkpoints: Path) -> str:
    """models/manifest.json for the checkpoints in CHECKPOINTS, read from the run's checkpoints/."""
    by_step = {row["step"]: row for row in rows}
    entries = []
    for step, what in CHECKPOINTS.items():
        path = checkpoints / f"step_{step:07d}.pt"
        row = by_step[step]
        counters = checkpoint_counters(path)
        if [counters.get(key) for key in ("steps", "generated", "games")] != [step, row["generated"], row["games"]]:
            raise SystemExit(f"{path.name}: its counters {counters} are not those of the metrics at step {step}")
        entries.append(
            {
                "file": path.name,
                "bytes": path.stat().st_size,
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "step": step,
                "samples": row["generated"],
                "games": row["games"],
                "date": datetime.fromtimestamp(row["time"]).astimezone().isoformat(timespec="seconds"),
                "what": what,
            }
        )
    note = (
        "PyTorch checkpoints written by tafl.train, not distributed with this repository: the network's "
        "configuration and weights, and the trainer's counters (samples and self-play games generated by that "
        "step). tafl.model.load_model reads them. The date is when the metrics of that step were logged, just "
        "before the checkpoint was saved."
    )
    return json.dumps({"note": note, "models": entries}, indent=2) + "\n"


def write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT).as_posix()} ({path.stat().st_size:,} bytes)")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("run", type=Path, help="the training run's folder, e.g. runs/r1")
    args = parser.parse_args(argv)
    name = args.run.resolve().name
    TRAINING.mkdir(exist_ok=True)
    shutil.copyfile(args.run / "config.json", TRAINING / f"{name}-config.json")
    print(f"wrote training/{name}-config.json")
    rows = metrics_rows(args.run / "metrics.jsonl")
    write(TRAINING / f"{name}-metrics.csv", metrics_csv(rows))
    write(TRAINING / f"{name}-events.txt", events(args.run / "log.txt"))
    write(MODELS / "manifest.json", manifest(rows, args.run / "checkpoints"))
    blocks, torn, partial = selfplay_blocks(args.run / "selfplay" / "games.jsonl")
    write(TRAINING / f"{name}-selfplay.csv", selfplay_csv(blocks, rows))
    total = sum(b["games"] for b in blocks)
    print(f"{total:,} self-play games; {torn} torn lines left out" + ("; a last line still being written" * partial))
    return 0


if __name__ == "__main__":
    sys.exit(main())
